            <span>En sterft niet anders dan als moslims.</span>
            <span> (Surah Aal Imran: Ayah 102)</span>
            <br>
            <span>Dit zijn door Allah de vastgestelde bepalingen en hij die Allah en Zijn boodschapper gehoorzaamt: Hij (Allah) zal hem het Paradijs binnenleiden, waar onder door de rivieren stromen. Zij zijn eeuwig levenden daarin. En dat is de geweldige overwinning.</span>
            <span>(Surah An-nisaa-e: Ayah 13)</span>
        </blockquote>
        <br>
        <p>Moge Allah de Verhevene diegene die op zoek is zijn naar de Waarheid helpen Zijn Weg te vinden en moge Allah de Verhevene de moslimgemeenschap zegenen. Amien.</p>

