        <h3>Islam binnentreden</h3>
        <h5>In de Naam van Allah de Erbarmer, de meest Barmhartige</h5>
        <br>
        <p>Het doel van dit artikel is om stap voor stap een uitleg te geven hoe iemand moslim wordt en de islam als religie accepteert. Een ‘moslim’ is degene die zich volledig onderwerpt aan Allah de Verhevene, de Schepper. Allah heeft niemand gedwongen om een religie aan te nemen, het is een keuze die men maakt en Allah de Alwetende heeft vele tekenen laten zien voor degenen die nadenkenen en de waarheid zoeken. Hij de Verhevene zegt in de Quran:</p>
        <blockquote>
            <span>En op de aarde zijn Tekens voor de overtuigden . En ook in jullie zelf, zien jullie dan niet?</span>
            <span>(Surah Ad-dzaarieyaat: Ayah 20-21).</span>
        </blockquote>
        <br>
        <p>De belangrijkste criteria om tot de islam toe te treden is het vergaren van voldoende basiskennis over de betekenis en doel van de Islam. Daarnaast ook de bedoeling te kennen van de ‘geloofsgetuigenis’ (shahada). De shahada en de gehele islam is gebaseerd op kennis.</p>
        <p>De “shahada” (geloofsgetuigenis) moet met jaqien (zekerheid) worden uitgesproken, zonder enige twijfel. Wanneer die zekerheid er is dan kan men de “shahada” afleggen. Allah de Verhevene is hier duidelijk over in de Quran:</p>
        <blockquote>
            <span>Alleen diegenen zijn de gelovigen die geloof hebben in Allah en Zijn boodschapper en niet hebben getwijfeld en hebben gestreden met hun rijkdom en hun Levens voor de Zaak van Allah, zij zijn de waarheidslievenden.</span>
            <span>(Surah Al Hoedjoerat: Ayah 15)</span>
        </blockquote>
        <br>
        <p>Verder zegt Allah de verhevene in de Quran:</p>
        <blockquote>
            <span>Voorwaar de enige godsdienst bij Allah is de Islam.</span>
            <span>(Surah Al Imran: Ayah 19)</span>
            <br>
            <span>En wie een andere godsdienst dan de Islam zoekt: het zal niet van hen aanvaard worden en hij behoort in het Hiernamaals tot de verliezers.</span>
            <span>(Surah Al Imran: Ayah 85)</span>
        </blockquote>
        <br>
        <p>Abdoellah Ibn Omar (moge Allah tevreden met hem zijn) verhaalde dat de Profeet (vrede zei met hem)</p>
        <p>Islam is gebaseerd op 5 pilaren:</p>
        <ul class="list">
            <li><p>1. Het getuigen dat er geen andere god is dan Allah (de Enige die alleen aanbeden moet worden) en dat Mohammed Zijn dienaar en boodschapper is. (Shahada)</p></li>
            <li><p>2. Het verrichten van het gebed (de 5 verplichte gebeden).</p></li>
            <li><p>3. Het betalen van Zakaat.</p></li>
            <li><p>4. De Hadj (de bedevaart) verrichten.</p></li>
            <li><p>5. Het vasten van Ramadan</p></li>
        </ul>
        <i>[Overgeleverd door: Boekharie, 8 en Moesliem, 16]</i>
        <br>
        <p>Men treedt tot de Islam door de shahada uit te spreken; de shahada wordt als volgt uitgesproken:</p>
        <blockquote>
            <span>Ash-hadoe allaa ielaaha iella llaah, wa ash-hadoe anna Moeh’ammadan rasoeloe laah</span>
        </blockquote>
        <br>
        <i>Betekenis: Ik getuig dat er geen god is naast Allah en ik getuig dat Mohammed Zijn boodschapper is.</i>
        <p>De persoon die de Islam binnentreedt moet kennis blijven opdoen over de Islam zodat het een totale levenswijze wordt. Dit zal desbetreffende persoon laten streven om een beter karakter te ontwikkelen en ook te streven naar perfectie. Het Licht van het geloof zal het hart van diegene vullen totdat zijn gehele lichaam gevuld is met geloof en gehoorzaamheid aan Allah de verhevene.</p>
        <p>De betekenis van het eerste deel van de Shahada “Ash-hadoe allaa ielaaha iella llaah” is ‘Ik getuig dat er geen andere god is dan Allah’. De grootste vorm van kennis is die kennis die leidt tot totale verwerping van valse afgoden en de volledige onderwerping van al onze intenties aan Allah alleen.</p>
        <p>Allah de Verhevene zegt in de Quran:</p>
        <blockquote>
            <span>Fa’lem annahoe la ilaha illa llaah</span>
            <span>Weet dat er geen god is dan Allah.</span>
            <span>(Surah Mohammed: Ayah 19)</span>
        </blockquote>
        <br>
        <p>Er is overgeleverd op gezag van ‘Oethmaan (moge Allah tevreden over hem zijn) dat de boodschapper van Allah (vrede zij met hem) zei:</p>
        <blockquote>
            <span>Diegene die sterft en er zich (volledig) bewust van is dat er geen God is dan Allah, betreedt het Paradijs.</span>
        </blockquote>
        <br>
        <i>[Moeslim]</i>
        <p>Dat wil zeggen: dat een moslim Allah’s wetten accepteert en ernaar handelt</p>
        <p>Naast het getuigen in de eenheid van Allah de boodschap van de profeet Mohammed (vrede zij met hem) dient men deze getuigenis uit te spreken en ernaar te handelen. Het is belangrijk Allah de Verhevene in zuivere aanbidding te aanbidden, in de zin van het volgen van het zuivere monotheïsme.</p>
        <p>Zoals Allah de Verhevene zegt in de Quran:</p>
        <blockquote>
            <span>Zij werden niets anders aanbevolen dan Allah met zuivere aanbidding te aanbidden.</span>
            <span>(Surah Al Bayyinah: Ayah 5)</span>
        </blockquote>
        <br>
        <p>De getuigenis betekent ook het volgen van Allah’s oordelen en wetten en het accepteren van de wetten van Allah de Verhevene. De wetten en oordelen van Allah dienen volledig geaccepteerd te worden en niet gedeeltelijk aanvaard te worden. De Waarheid is de Quran en de Leringen van de profeet Mohammed (vrede zij met hem)</p>
        <p>De betekenis van het tweede gedeelte van de Sahada “wa ash-hadoe anna Moeh’ammadan rasoeloe llaah” is ik getuig dat Mohammed Zijn boodschapper is.</p>
        <p>Een moslim moet ook de boodschapper Mohammed (vrede zij met hem) gehoorzamen. Dit houdt in; te geloven in wat hij (vrede zij met hem) heeft gezegd, zijn (vrede zij met hem) leringen te praktiseren en te vermijden wat hij (vrede zij met hem) heeft verboden gesteld. De Boodschap die de boodschapper Mohammed (vrede zij met hem) bracht was aan hem (vrede zij met hem) geopenbaard door Allah, Geprezen en Verheven is Hij.</p>
        <blockquote>
            <span>Bij jou Heer. Zij kunnen geen geloof hebben totdat zij jou (profeet Mohammed) tot rechter maken bij al hun meningsverschillen en in zichzelf geen weerstand vinden tegen wat jij oordeelde, en deze accepteren het dan volledig.</span>
            <span>(Surah An Nisa: Ayah 65)</span>
        </blockquote>
        <br>
        <p>Wanneer men de shahada met liefde en volledig onderwerping uitspreekt, dan accepteert men de voorwaarde van de shahada met liefde. Men houdt het meest van zijn Schepper boven al het andere. Diegene die van Allah de Verhevene houdt zal van zijn religie houden.</p>
        <p>Zoals Allah de Verhevene in de Quran:</p>
        <blockquote>
            <span>En degenen die geloven zijn sterker in hun liefde voor Allah (boven al het andere).</span>
            <span>(Surah Al Baqarah: Ayah 165)</span>
        </blockquote>
        <br>
        <p>En als laatste deze 2 verzen uit de Qor-aan om over na te denken:</p>
